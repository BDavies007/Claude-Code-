import { Sun, CheckCircle2, CalendarClock, Target, AlertTriangle } from "lucide-react";
import { createClient } from "@/lib/supabase/server";
import { getDashboardData } from "@/lib/data/queries";
import { PageHeader } from "@/components/shared/page-header";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { RegenerateButton } from "@/components/daily-brief/regenerate-button";
import { formatCurrency, formatTime, formatDate } from "@/lib/utils";
import { RiskLevelBadge } from "@/components/shared/status-badges";

export const dynamic = "force-dynamic";

export default async function DailyBriefPage() {
  const supabase = createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  const { data: profile } = await supabase
    .from("profiles")
    .select("full_name")
    .eq("id", user!.id)
    .maybeSingle();

  const { brief, tasks, meetings, risks, openOpps, pipelineValue } =
    await getDashboardData();

  const firstName = (profile?.full_name ?? "").split(" ")[0] || "there";
  const dateLabel = new Date().toLocaleDateString("en-US", {
    weekday: "long",
    month: "long",
    day: "numeric",
    year: "numeric",
  });

  return (
    <>
      <PageHeader
        title="Daily Brief"
        description={dateLabel}
      >
        <RegenerateButton hasBrief={!!brief} />
      </PageHeader>

      {/* AI summary */}
      <Card className="mb-6 border-electric-500/30 bg-electric-500/[0.06]">
        <CardContent className="p-6">
          <div className="flex items-center gap-2">
            <div className="flex h-9 w-9 items-center justify-center rounded-lg bg-electric-500/20">
              <Sun className="h-5 w-5 text-electric-400" />
            </div>
            <div>
              <p className="text-xs uppercase tracking-wide text-electric-400">
                Generated by Amelia · Chief of Staff
              </p>
              <h2 className="text-lg font-semibold">
                {brief?.headline ?? `Good day, ${firstName}`}
              </h2>
            </div>
          </div>

          {brief?.summary ? (
            <p className="mt-4 leading-relaxed text-foreground/90">
              {brief.summary}
            </p>
          ) : (
            <p className="mt-4 leading-relaxed text-muted-foreground">
              No brief has been generated for today yet. Click{" "}
              <span className="font-medium text-foreground">Generate brief</span>{" "}
              to have Amelia synthesise your tasks, meetings, pipeline, and risks
              into a focused morning brief.
            </p>
          )}

          {brief?.highlights && brief.highlights.length > 0 && (
            <ul className="mt-5 space-y-2">
              {brief.highlights.map((h, i) => (
                <li key={i} className="flex items-start gap-2.5">
                  <CheckCircle2 className="mt-0.5 h-4 w-4 shrink-0 text-electric-400" />
                  <span className="text-sm text-foreground/90">{h}</span>
                </li>
              ))}
            </ul>
          )}
        </CardContent>
      </Card>

      {/* Supporting context */}
      <div className="grid grid-cols-1 gap-4 lg:grid-cols-2">
        <Card>
          <CardHeader className="pb-3">
            <CardTitle className="flex items-center gap-2 text-sm">
              <CalendarClock className="h-4 w-4 text-electric-400" /> Today&apos;s
              schedule
            </CardTitle>
          </CardHeader>
          <CardContent className="pt-0">
            {meetings.length ? (
              <ul className="divide-y divide-border/60">
                {meetings.map((m) => (
                  <li key={m.id} className="flex items-center justify-between gap-3 py-2.5 first:pt-0 last:pb-0">
                    <span className="truncate text-sm">{m.title}</span>
                    <span className="whitespace-nowrap text-xs text-muted-foreground">
                      {formatDate(m.starts_at)} · {formatTime(m.starts_at)}
                    </span>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="py-4 text-sm text-muted-foreground">
                No meetings scheduled.
              </p>
            )}
          </CardContent>
        </Card>

        <Card>
          <CardHeader className="pb-3">
            <CardTitle className="flex items-center gap-2 text-sm">
              <CheckCircle2 className="h-4 w-4 text-electric-400" /> Open tasks
            </CardTitle>
          </CardHeader>
          <CardContent className="pt-0">
            {tasks.length ? (
              <ul className="divide-y divide-border/60">
                {tasks.slice(0, 6).map((t) => (
                  <li key={t.id} className="flex items-center justify-between gap-3 py-2.5 first:pt-0 last:pb-0">
                    <span className="truncate text-sm">{t.title}</span>
                    <Badge variant="neutral">{t.priority}</Badge>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="py-4 text-sm text-muted-foreground">
                No open tasks.
              </p>
            )}
          </CardContent>
        </Card>

        <Card>
          <CardHeader className="pb-3">
            <CardTitle className="flex items-center gap-2 text-sm">
              <Target className="h-4 w-4 text-electric-400" /> Pipeline focus
            </CardTitle>
          </CardHeader>
          <CardContent className="pt-0">
            <p className="mb-3 text-sm text-muted-foreground">
              {formatCurrency(pipelineValue)} across {openOpps.length} live
              opportunities.
            </p>
            {openOpps.length ? (
              <ul className="divide-y divide-border/60">
                {openOpps.slice(0, 4).map((o) => (
                  <li key={o.id} className="flex items-center justify-between gap-3 py-2.5 first:pt-0 last:pb-0">
                    <span className="truncate text-sm">{o.name}</span>
                    <span className="whitespace-nowrap text-xs font-medium">
                      {formatCurrency(o.value, o.currency)}
                    </span>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="py-2 text-sm text-muted-foreground">
                No live opportunities.
              </p>
            )}
          </CardContent>
        </Card>

        <Card>
          <CardHeader className="pb-3">
            <CardTitle className="flex items-center gap-2 text-sm">
              <AlertTriangle className="h-4 w-4 text-electric-400" /> Risks to
              watch
            </CardTitle>
          </CardHeader>
          <CardContent className="pt-0">
            {risks.length ? (
              <ul className="divide-y divide-border/60">
                {risks.map((r) => (
                  <li key={r.id} className="flex items-start justify-between gap-3 py-2.5 first:pt-0 last:pb-0">
                    <span className="truncate text-sm">{r.title}</span>
                    <RiskLevelBadge value={r.level} />
                  </li>
                ))}
              </ul>
            ) : (
              <p className="py-4 text-sm text-muted-foreground">
                No open risks.
              </p>
            )}
          </CardContent>
        </Card>
      </div>
    </>
  );
}
